import {spawn} from 'node:child_process';
import {mkdir, readFile, writeFile, symlink, chmod} from 'node:fs/promises';
import {accessSync, constants} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = path.join(root, 'node_modules/.bin/supabase');
const runtime = path.join(root, '.local');
const dockerBin = path.join(runtime, 'docker-bin');
let realDocker;
for (const directory of (process.env.PATH ?? '').split(path.delimiter)) {
  const candidate = path.join(directory, 'docker');
  if (candidate === path.join(dockerBin, 'docker')) continue;
  try {accessSync(candidate, constants.X_OK); realDocker = candidate; break;} catch {}
}
await mkdir(dockerBin, {recursive:true});
await chmod(path.join(root,'scripts/docker-local.cjs'), 0o755);
try {await symlink(path.join(root,'scripts/docker-local.cjs'), path.join(dockerBin,'docker'));} catch(error) {if (error.code !== 'EEXIST') throw error;}

const marker = '# Generated by Lumi local Supabase. Local development only.';

function run(args) {
  return new Promise((resolve, reject) => {
    const child = spawn(cli, args, {cwd: root, env: {...process.env, SUPABASE_HOME: path.join(runtime, 'supabase-home'), PATH: `${dockerBin}${path.delimiter}${process.env.PATH}`, LUMI_DOCKER_BINARY: realDocker}, stdio: ['ignore', 'pipe', 'pipe']});
    let output = ''; let error = '';
    child.stdout.on('data', chunk => {output += chunk;});
    child.stderr.on('data', chunk => {error += chunk;});
    child.on('error', reject);
    child.on('close', code => code === 0 ? resolve(output) : reject(new Error(scrub(error + '\n' + output))));
  });
}
function scrub(text) {
  return text.replace(/eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, '[redacted]')
    .split('\n').filter(line => !/secret|service.role|anon.key|publishable.key|password|postgres(?:ql)?:\/\//i.test(line)).slice(-45).join('\n');
}
async function configure() {
  const data = JSON.parse(await run(['status', '-o', 'json']));
  if (!data.API_URL || !data.ANON_KEY) throw new Error('Supabase local não retornou URL e chave pública.');
  const envPath = path.join(root, 'apps/painel/.env.local');
  let existing = '';
  try {existing = await readFile(envPath, 'utf8');} catch (error) {if (error.code !== 'ENOENT') throw error;}
  if (existing && !existing.startsWith(marker)) throw new Error('apps/painel/.env.local já existe e foi preservado. Configure a conexão local manualmente; veja docs/supabase-local.md.');
  // These are local public settings. Never write or print service-role/admin keys.
  await writeFile(envPath, `${marker}\nNEXT_PUBLIC_SUPABASE_URL=${data.API_URL}\nNEXT_PUBLIC_SUPABASE_ANON_KEY=${data.ANON_KEY}\n`, {mode: 0o600});
  await mkdir(runtime, {recursive: true});
  await writeFile(path.join(runtime, 'supabase-public.json'), JSON.stringify({url:data.API_URL, anonKey:data.ANON_KEY}), {mode:0o600});
  console.log('Supabase local disponível. Configuração pública gravada em apps/painel/.env.local (ignorado pelo Git).');
}
try {
  const action = process.argv[2];
  if (action === 'start') {
    console.log('Iniciando Supabase local. A primeira execução baixa as imagens Docker; pode levar alguns minutos.');
    await run(['start']);
    await run(['migration', 'up']);
    await configure();
  } else if (action === 'migrate') {
    await run(['migration', 'up']);
    console.log('Migrations locais aplicadas.');
  } else if (action === 'stop') {
    await run(['stop']);
    console.log('Supabase local parado; dados preservados pelo CLI.');
  } else if (action === 'configure') {
    await configure();
  } else throw new Error('Use start, stop, configure ou migrate.');
} catch (error) {console.error(scrub(error.message)); process.exitCode = 1;}
